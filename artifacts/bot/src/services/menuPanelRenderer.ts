/** Notion N14 M1/M2: two different menus, ONE @GayBBS_bot and MPB owner.
 * Never fabricate Telegram message IDs, topic IDs, Cloudflare Pages URLs,
 * missing functionality or links to a disabled document.
 */
export type NavLink={label:string;url:string;verified:boolean};
export type EntryLink={feature:"profile"|"announcement"|"room"|"link"|"search";url:string;ready:boolean};
export type PanelSpec={
 type:"general_guide"|"posting";
 board:"area_bbs"|"video_chat"|"gay_board";
 links:readonly NavLink[];
 entryLinks:readonly EntryLink[];
};
export type ButtonSpec={text:string;url:string};
export type RenderedPanel={text:string;rows:ButtonSpec[][]};
function safeUrl(url:string):boolean{
 try{
  const x=new URL(url);
  return x.protocol==="https:"&&!x.username&&!x.password&&
   (x.hostname==="t.me"||x.hostname==="telegram.me"||
    x.hostname.endsWith(".pages.dev")||x.hostname==="g-acebot.com"||
    x.hostname.endsWith(".g-acebot.com"));
 }catch{return false;}
}
function assertPublishedLink(link:NavLink|EntryLink):void{
 if(!safeUrl(link.url)||!("verified" in link?link.verified:link.ready))
  throw new Error("PANEL_LINK_NOT_VERIFIED");
}
export function renderMenuPanel(spec:PanelSpec):RenderedPanel{
 if(!["area_bbs","video_chat","gay_board"].includes(spec.board))
  throw new Error("PANEL_BOARD_INVALID");
 const seen=new Set<string>();
 const rows:ButtonSpec[][]=[];
 const add=(label:string,url:string)=>{
  if(!label.trim()||label.length>64||seen.has(label)||!safeUrl(url))
   throw new Error("PANEL_LINK_DUPLICATE_OR_INVALID");
  seen.add(label);rows.push([{text:label,url}]);
 };
 if(spec.type==="general_guide"){
  // M1: guide/navigation only. Content is a preapproved existing permanent
  // Telegram post; never put an editing control on the public guide menu.
  for(const item of spec.links){
   assertPublishedLink(item);
   add(item.label,item.url);
  }
  if(!rows.length)throw new Error("PANEL_GUIDE_EMPTY");
  return {text:"📌 総合案内\n各ボタンから既存の案内・トピックへ移動できます。",rows};
 }
 if(spec.type!=="posting")throw new Error("PANEL_TYPE_INVALID");
 // M2: fixed Topic-specific entry. Start token is generated by the server
 // and resolved to the originating chat/thread in the DB.
 const name:Record<EntryLink["feature"],string>={
  profile:"【🪪】プロフ作成",
  search:"【🔍️】検索・フィルター",
  announcement:"【📢】相手募集",
  room:"【🎬】ROOM作成",
  link:"【🔲】🔗ボタン作成",
 };
 for(const item of spec.entryLinks){
  if(!item.ready)continue; // No clickable placeholder for disabled features.
  assertPublishedLink(item);
  add(name[item.feature],item.url);
 }
 for(const item of spec.links){assertPublishedLink(item);add(item.label,item.url);}
 if(!rows.length)throw new Error("PANEL_POSTING_EMPTY");
 return {text:"📝 投稿メニュー\nこのトピックからBotのDMへ移動し、下書き・公開先を確認できます。",rows};
}
